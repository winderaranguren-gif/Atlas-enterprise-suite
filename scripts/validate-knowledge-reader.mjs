import { Script } from 'node:vm';
import { readFile } from 'node:fs/promises';
import { knowledgeReaderRoutes } from '../modules/knowledge-reader.js';

const fail=message=>{throw new Error(`[knowledge-reader] ${message}`)};
const assert=(condition,message)=>{if(!condition)fail(message)};
const url=new URL('https://atlas.validation.local/platform/knowledge-reader');
const response=await knowledgeReaderRoutes(new Request(url,{method:'GET'}),{},url);
assert(response?.status===200,'Knowledge Reader route must return 200 before outer auth wrapping');
const body=await response.text();

for(const marker of [
  'ATLAS Knowledge Reader','Build reader','Search current document','Outline','Bookmarks','Section notes',
  'Review prompts','Local-only workspace','No proprietary course library','accept=".txt,.md,text/plain,text/markdown"',
  'Prompts are generated deterministically','Durable learner records remain in ATLAS HR Training.'
])assert(body.includes(marker),`Knowledge Reader missing ${marker}`);

for(const marker of ['localStorage','crypto','CSS.escape','navigator.clipboard','File','viewed','bookmarks','notes','condition']){
  if(marker==='condition')continue;
  assert(body.includes(marker),`Knowledge Reader missing browser capability/state marker ${marker}`);
}
for(const prohibited of ['fetch(','XMLHttpRequest','/api/upload','proprietary course content included','AI-generated by external service'])assert(!body.includes(prohibited),`Knowledge Reader must remain local/authorized-content only: ${prohibited}`);

const scripts=[...body.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(match=>match[1]);
assert(scripts.length===1,'Knowledge Reader must have one local browser script');
try{new Script(scripts[0],{filename:'atlas-knowledge-reader.browser.js'})}catch(error){fail(`Knowledge Reader browser script does not compile: ${error.message}`)}

const worker=await readFile(new URL('../worker-crm.js',import.meta.url),'utf8');
assert(worker.includes("import { knowledgeReaderRoutes } from './modules/knowledge-reader.js';"),'protected runtime must import Knowledge Reader');
assert(worker.includes("url.pathname==='/platform/knowledge-reader'"),'protected runtime must intercept Knowledge Reader route');
assert(worker.includes('verifiedWorkspaceResponse(request,env,url,workspace)'),'Knowledge Reader must pass browser-session verification');
assert(worker.includes("url.pathname==='/platform/hr-payroll/training'&&!body.includes('href=\"/platform/knowledge-reader\"')"),'HR Training must expose Knowledge Reader launcher');
assert(worker.includes('Open ATLAS Knowledge Reader'),'HR Training launcher label missing');

console.log('ATLAS Knowledge Reader gate passed: local import, outline/search, progress, bookmarks, notes, review prompts, protected routing and HR Training handoff verified.');
