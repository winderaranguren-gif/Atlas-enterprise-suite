import { readFile, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

function assert(v,m){if(!v)throw new Error(m)}
const py=spawnSync('python3',['-m','py_compile','atlas/trainers/canary_train.py'],{encoding:'utf8'});
assert(py.status===0,py.stderr||'canary trainer syntax failed');
const run=spawnSync(process.execPath,['atlas/model-factory.mjs'],{encoding:'utf8'});
assert(run.status===0,`${run.stdout}\n${run.stderr}`);
const model=JSON.parse(await readFile('build/models/atlas-audio-canary-v1.json','utf8'));
const result=JSON.parse(await readFile('build/models/atlas-audio-canary-v1-result.json','utf8'));
assert(model.model==='ATLAS Audio Canary v1','model name mismatch');
assert(model.kind==='neural-canary','model kind mismatch');
assert(model.productionCapability===false,'canary falsely marked production-capable');
assert(Array.isArray(model.externalProviders)&&model.externalProviders.length===0,'external provider detected');
assert(model.metrics.holdoutAccuracy>=0.90,`accuracy gate failed: ${model.metrics.holdoutAccuracy}`);
const actual=createHash('sha256').update(await readFile('build/models/atlas-audio-canary-v1.json')).digest('hex');
assert(actual===result.sha256,'model artifact hash mismatch');
assert(result.state==='candidate-canary','candidate state mismatch');
const src=await readFile('atlas/trainers/canary_train.py','utf8');
for(const token of ['cross-entropy','tanh','weights','deterministic synthetic audio-feature vectors generated by ATLAS'])assert(src.includes(token),`trainer missing ${token}`);
console.log(JSON.stringify({ok:true,model:model.model,accuracy:model.metrics.holdoutAccuracy,sha256:actual,state:model.state,externalProviders:0},null,2));
await rm('build/models',{recursive:true,force:true});
